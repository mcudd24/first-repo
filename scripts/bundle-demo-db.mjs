// Bundles the seeded SQLite database into a TypeScript module so zero-config
// deploys (e.g. Vercel with no DATABASE_URL) can bootstrap a working demo DB
// into the serverless tmp dir at runtime.
//
// Usage: npm run db:bundle-demo   (runs db:reset first for a clean snapshot)

import { readFileSync, writeFileSync } from "fs";
import { resolve } from "path";

const dbPath = resolve("prisma/dev.db");
const outPath = resolve("src/server/demo-db.generated.ts");

const bytes = readFileSync(dbPath);
const base64 = bytes.toString("base64");

writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/bundle-demo-db.mjs — do not edit by hand.
// Seeded SQLite database (${(bytes.length / 1024).toFixed(0)} KB) used when no
// DATABASE_URL is configured, e.g. a zero-config Vercel preview deploy.

export const DEMO_DB_BASE64 =
  "${base64}";
`
);

console.log(`Bundled ${dbPath} (${(bytes.length / 1024).toFixed(0)} KB) -> ${outPath}`);
